"""Generate the Excel Yield Analyzer V1.8 PowerPoint user guide."""
from __future__ import annotations

from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

OUTPUT_NAME = "Excel_Yield_Analyzer_V1.8_User_Guide.pptx"


def add_title(slide, title: str) -> None:
    box = slide.shapes.add_textbox(Inches(.55), Inches(.25), Inches(12.2), Inches(.55))
    paragraph = box.text_frame.paragraphs[0]
    paragraph.text = title
    paragraph.font.size = Pt(24)
    paragraph.font.bold = True
    paragraph.font.color.rgb = RGBColor(31, 78, 121)


def add_bullets(slide, bullets: list[str]) -> None:
    box = slide.shapes.add_textbox(Inches(.75), Inches(1.15), Inches(11.7), Inches(5.7))
    text_frame = box.text_frame
    text_frame.clear()
    for index, text in enumerate(bullets):
        paragraph = text_frame.paragraphs[0] if index == 0 else text_frame.add_paragraph()
        paragraph.text = text
        paragraph.level = 0
        paragraph.font.size = Pt(20)
        paragraph.space_after = Pt(10)


def add_section(prs: Presentation, title: str, bullets: list[str]) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_title(slide, title)
    add_bullets(slide, bullets)


def main() -> int:
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    slide = prs.slides.add_slide(prs.slide_layouts[6])
    title = slide.shapes.add_textbox(Inches(.8), Inches(2.1), Inches(11.7), Inches(1.2))
    title.text_frame.text = "Excel Yield Analyzer"
    title.text_frame.paragraphs[0].font.size = Pt(34)
    title.text_frame.paragraphs[0].font.bold = True
    title.text_frame.paragraphs[0].font.color.rgb = RGBColor(31, 78, 121)
    title.text_frame.paragraphs[0].alignment = PP_ALIGN.CENTER

    subtitle = slide.shapes.add_textbox(Inches(.8), Inches(3.35), Inches(11.7), Inches(.8))
    subtitle.text_frame.text = "V1.8 Debug — User Guide"
    subtitle.text_frame.paragraphs[0].font.size = Pt(24)
    subtitle.text_frame.paragraphs[0].alignment = PP_ALIGN.CENTER

    add_section(prs, "Opening the application", [
        "Run from source with Python 3.15, or open the macOS .app bundle.",
        "The analyzer loads an empty workspace on startup.",
        "Use Open measurements for a measurement workbook.",
        "Use Open unit mapping for an optional mapping workbook.",
    ])

    add_section(prs, "Import measurement data", [
        "Fleet Data - PE Format: uses the existing PE parser and column recognition.",
        "Fleet Data - Insight Raw: select the worksheet and enter the Excel row containing headers.",
        "Example header rows: 2, 5, 8, or 12.",
        "For multiple sheets, choose whether to open each sheet in a separate window.",
    ])

    add_section(prs, "Insight Raw cleaning", [
        "The selected header row becomes dataframe column names.",
        "Data starts on the row immediately after the selected header.",
        "Rows with blank, empty, whitespace-only, or NaN column C are removed.",
        "The cleaned dataframe is reset before existing column recognition is applied.",
        "Only required measurement columns are converted with pd.to_numeric(errors='coerce').",
    ])

    add_section(prs, "Configure the analysis", [
        "Choose the Unit/serial key column.",
        "Choose Vendor and Breakdown fields.",
        "Select Vendor values and Breakdown values.",
        "Select one or more numeric measurement columns.",
        "Choose the chart types to build.",
    ])

    add_section(prs, "Specification setup", [
        "Single Spec: enter USL, Target/Nominal, and LSL.",
        "Multi Spec: add rows containing Start Point, End Point, USL, Target, and LSL.",
        "Spec ranges must be valid for the selected measurement-axis columns.",
        "The green Target/Nominal line displays only the numeric value beside the line.",
    ])

    add_section(prs, "Pass/Fail chart behavior", [
        "Pass Units form the stable baseline population.",
        "Default state: show all Pass Units and no Fail Units.",
        "Select one Fail SN: keep all Pass Units and show only that Fail SN.",
        "Select multiple Fail SNs: keep all Pass Units and show only selected Fail SNs.",
        "Clear the selection: return to Pass Units only.",
    ])

    add_section(prs, "Fail SN List", [
        "Enable Show Fail / out-of-spec units.",
        "Rows are generated by the existing Fail SN / fail-position calculation.",
        "Use row selection in the Fail SN table to update the chart.",
        "Single and multi-row selection are both supported.",
        "The Pass Unit population never disappears during Fail SN selection.",
    ])

    add_section(prs, "Vendor Pass/Fail Commonality", [
        "The summary table remains visible and functional.",
        "It shows Pass N, Fail N, percentages, and total unit counts.",
        "Example: 159 Pass Units and 1 Fail Unit.",
        "A selected Fail chart should contain 159 Pass Units plus 1 selected Fail Unit.",
    ])

    add_section(prs, "Chart and report actions", [
        "Build chart creates one page per selected chart type.",
        "Use navigation arrows to move between chart pages.",
        "Save PNG exports the current chart.",
        "Save PDF exports the selected report contents.",
        "Export Excel creates chart, statistics, summary, Fail SN, spec, and data sheets.",
    ])

    add_section(prs, "Build the macOS .app", [
        "Install dependencies and ensure Python 3.15 is available.",
        "Run: python3.15 build_macos_app.py",
        "Open: open \"dist/Excel Yield Analyzer V1.8.app\"",
        "The generated bundle is under dist/Excel Yield Analyzer V1.8.app.",
    ])

    add_section(prs, "Validation checklist", [
        "Confirm the Vendor table reports Pass N and Fail N correctly.",
        "Confirm default chart has Pass Units and no Fail Units.",
        "Confirm selected Fail SNs add only selected failures to the Pass baseline.",
        "Confirm clearing the selection returns to Pass Units only.",
        "Run python -m pytest -v before release.",
    ])

    output = Path(__file__).resolve().parent / OUTPUT_NAME
    prs.save(output)
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
